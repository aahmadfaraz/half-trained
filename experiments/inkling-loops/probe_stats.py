"""Descriptive stats from the probe (PREREG change of 22 Nov): no hypothesis tests.
python3 probe_stats.py OUT.md DIR [DIR ...]   (DIR holds probe_loops{n}.npz/.json and prompts.json)"""
import glob
import json
import os
import re
import statistics as st
import sys
from collections import defaultdict

import numpy as np

N_PHYS, START, END = 24, 6, 18
CORE = END - START


def slot(ip, p):
    return ip if p == 1 or ip < START or ip >= END else N_PHYS + (p - 2) * CORE + (ip - START)


def load(dirs):
    arrs, meta, answers = {}, {}, {}
    for d in dirs:
        pj = os.path.join(d, "prompts.json")
        if os.path.exists(pj):
            answers.update({it["id"]: it["ans"] for it in json.load(open(pj, encoding="utf-8"))["items"]})
        for f in glob.glob(os.path.join(d, "probe_loops*.npz")):
            n = int(re.search(r"loops(\d+)", f).group(1))
            z = np.load(f)
            arrs[n] = {k: z[k] for k in z.files}
            meta[n] = {r["id"]: r for r in json.load(open(f[:-4] + ".json", encoding="utf-8"))}
    return arrs, meta, answers


def get(arrs, n, pid, name, ip, p):
    return arrs[n].get(f"{pid}|{name}-{slot(ip, p)}")


def rel(a, b):
    return float(np.linalg.norm(a - b) / (np.linalg.norm(b) + 1e-12))


def cos(a, b):
    return float(a @ b / (np.linalg.norm(a) * np.linalg.norm(b) + 1e-12))


def first_int(text):
    nums = re.findall(r"-?\d[\d,]*", (text or "").split("<|end_message|>")[0].replace(" ", ""))
    return int(nums[-1].replace(",", "")) if nums else None


def main():
    out_md, dirs = sys.argv[1], sys.argv[2:]
    arrs, meta, answers = load(dirs)
    loops = sorted(arrs)
    big = max(loops)
    ids = sorted(meta[big])
    arith = [i for i in ids if i != "cat"]
    L, J = ["# Inkling loops: probe stats (generated by probe_stats.py)"], {"loops": loops}
    any_l = next(k for k in arrs[big] if "|l_out-" in k)
    n_embd = arrs[big][any_l].size
    topk_sizes = sorted({v.size for k, v in arrs[big].items() if "|ffn_moe_topk-" in k})
    L.append(f"\nLoop counts found: {loops}. Prompts at {big} loops: {len(ids)}. State size (n_embd): {n_embd}. Expert ids per layer: {topk_sizes}.")
    J["n_embd"] = n_embd

    L.append("\n## 1. Is pass k the same whatever the dial says? (last loop layer, physical 17)\n")
    L.append("| Pass | compared loop counts | max relative difference over prompts |\n|---|---|---|")
    J["consistency"] = {}
    for p in range(1, big + 1):
        ns = [n for n in loops if n >= p]
        if len(ns) < 2:
            continue
        worst = 0.0
        for pid in ids:
            ref = get(arrs, ns[-1], pid, "l_out", END - 1, p)
            for n in ns[:-1]:
                x = get(arrs, n, pid, "l_out", END - 1, p)
                if ref is not None and x is not None:
                    worst = max(worst, rel(x, ref))
        J["consistency"][p] = worst
        L.append(f"| {p} | {ns} | {worst:.2e} |")

    L.append(f"\n## 2. How much each pass changes the thought (output of the last loop layer, {big}-loop run)\n")
    L.append("Relative change = |pass k − pass k−1| / |pass k−1|. Cosine = similarity of the two states (1 = same direction).\n")
    L.append("| Pass | arithmetic: mean / median relative change | mean cosine | 'The cat sat on the' |\n|---|---|---|---|")
    J["change"] = {}
    for p in range(2, big + 1):
        ch, cs = [], []
        for pid in arith:
            a, b = get(arrs, big, pid, "l_out", END - 1, p), get(arrs, big, pid, "l_out", END - 1, p - 1)
            ch.append(rel(a, b))
            cs.append(cos(a, b))
        cat = "-"
        if "cat" in ids:
            cat = f"{rel(get(arrs, big, 'cat', 'l_out', END - 1, p), get(arrs, big, 'cat', 'l_out', END - 1, p - 1)):.3f}"
        J["change"][p] = {"mean": st.mean(ch), "median": st.median(ch), "cos": st.mean(cs), "cat": cat}
        L.append(f"| {p} | {st.mean(ch):.3f} / {st.median(ch):.3f} | {st.mean(cs):.3f} | {cat} |")

    L.append(f"\n## 3. Final state: how much does one more pass change what reaches the output? (layer 23 output, run n vs run n−1)\n")
    L.append("| Loops | arithmetic: mean relative change vs one loop fewer |\n|---|---|")
    J["final_change"] = {}
    for n in loops:
        if n - 1 not in arrs:
            continue
        ch = [rel(arrs[n][f"{pid}|l_out-23"], arrs[n - 1][f"{pid}|l_out-23"]) for pid in arith
              if f"{pid}|l_out-23" in arrs[n] and f"{pid}|l_out-23" in arrs[n - 1]]
        if ch:
            J["final_change"][n] = st.mean(ch)
            L.append(f"| {n - 1} → {n} | {st.mean(ch):.3f} |")

    L.append(f"\n## 4. Experts: does a pass reuse the experts of the pass before? ({big}-loop run, loop layers 6-17, 8 of 128 per layer)\n")
    L.append("Chance overlap of two random picks of 8 from 128 = 0.5 of 8. 'Other prompts' = same layer and pass, two different prompts.\n")
    L.append("| Pass | same as pass k−1 (mean of 8) | same as pass 1 | other prompts, same pass |\n|---|---|---|---|")
    J["experts"] = {}
    for p in range(1, big + 1):
        prev, first, other = [], [], []
        for ip in range(START, END):
            picks = {pid: get(arrs, big, pid, "ffn_moe_topk", ip, p) for pid in arith}
            picks = {k: set(v.tolist()) for k, v in picks.items() if v is not None}
            if not picks:
                continue
            ks = sorted(picks)
            for i, a in enumerate(ks):
                for b in ks[i + 1:i + 4]:
                    other.append(len(picks[a] & picks[b]))
            if p > 1:
                for pid in ks:
                    q = get(arrs, big, pid, "ffn_moe_topk", ip, p - 1)
                    f = get(arrs, big, pid, "ffn_moe_topk", ip, 1)
                    prev.append(len(picks[pid] & set(q.tolist())))
                    first.append(len(picks[pid] & set(f.tolist())))
        if not other:
            continue
        J["experts"][p] = {"prev": st.mean(prev) if prev else None, "first": st.mean(first) if first else None, "other": st.mean(other)}
        L.append(f"| {p} | {st.mean(prev):.2f} | {st.mean(first):.2f} | {st.mean(other):.2f} |" if prev else f"| {p} | - | - | {st.mean(other):.2f} |")

    L.append("\n## 5. The answer at each loop count (forced silent, greedy) = what it says if it stops after pass n\n")
    L.append("| Loops | correct of " + str(len(arith)) + " | mean top-1 probability of the first answer token |\n|---|---|---|")
    J["answers"] = defaultdict(dict)
    for n in loops:
        ok, pt = 0, []
        for pid in arith:
            r = meta[n].get(pid)
            if not r:
                continue
            g = first_int(r["generated"])
            ok += g == answers.get(pid)
            pt.append(r["steps"][0][0][2] if r["steps"] else 0)
            J["answers"][pid][n] = {"got": g, "ok": g == answers.get(pid), "top": [s[:3] for s in r["steps"][0][:5]] if r["steps"] else []}
        L.append(f"| {n} | {ok} | {st.mean(pt):.3f} |")
    L.append("\nPer problem (✓ right, ✗ wrong, the number it gave):\n")
    L.append("| Problem | answer | " + " | ".join(f"{n} loop{'s' if n > 1 else ''}" for n in loops) + " |")
    L.append("|---" * (len(loops) + 2) + "|")
    for pid in arith:
        cells = []
        for n in loops:
            a = J["answers"][pid].get(n)
            cells.append("-" if not a else f"{'✓' if a['ok'] else '✗'} {a['got']}")
        L.append(f"| {pid} | {answers.get(pid)} | " + " | ".join(cells) + " |")
    if "cat" in ids:
        L.append("\n'The cat sat on the' (no chat template): top 5 next tokens\n")
        J["cat"] = {}
        for n in loops:
            r = meta[n].get("cat")
            if r and r["steps"]:
                top = [(s[1], round(s[2], 3)) for s in r["steps"][0][:5]]
                J["cat"][n] = {"top": top, "generated": r["generated"]}
                L.append(f"- {n} loop{'s' if n > 1 else ''}: " + ", ".join(f"{json.dumps(t)} {p:.3f}" for t, p in top) + f" → \"{r['generated']}\"")

    sil = {}
    for d in dirs:
        for f in glob.glob(os.path.join(d, "silent_loops*.json")):
            n = int(re.search(r"loops(\d+)", f).group(1))
            sil[n] = {r["id"]: r["generated"] for r in json.load(open(f, encoding="utf-8"))}
    if sil:
        same = tot = 0
        for n in loops:
            for pid in arith:
                if n in sil and pid in sil[n] and pid in meta[n]:
                    tot += 1
                    same += first_int(sil[n][pid]) == first_int(meta[n][pid]["generated"])
        L.append(f"\nCheck: the probe's answers match the forced-silent run's answers on the same items in {same} of {tot} cases.")
        J["silent_match"] = [same, tot]

    open(out_md, "w").write("\n".join(L) + "\n")
    json.dump(J, open(out_md[:-3] + ".json", "w"), default=str, indent=1)
    print("\n".join(L))


main()
